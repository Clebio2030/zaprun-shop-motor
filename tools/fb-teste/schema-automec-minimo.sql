/* Schema MÍNIMO do Automec para testar a gravação de orçamento (ADR-306).
   Não é o schema real: são as colunas que as views dos clientes (Freitas,
   Fimade, Ligeirinho) e o srvPDV.Web da Pontual mostram existir, em
   CHARACTER SET NONE como no cliente. Serve ao tools/fb-teste/testar-orcamento.js.

   Criar (Firebird 3/4 em Docker):
     CREATE DATABASE '/firebird/data/automec.fdb' USER 'SYSDBA' PASSWORD 'masterkey'
       DEFAULT CHARACTER SET NONE;
*/
CREATE TABLE CONFIGURACAO (IDEMPRESA INTEGER NOT NULL PRIMARY KEY, CNPJ VARCHAR(20), NOMEEMPRESA VARCHAR(60));
CREATE TABLE VENDEDOR (CDVENDEDOR INTEGER NOT NULL PRIMARY KEY, VENDEDOR VARCHAR(50), TELEFONE VARCHAR(15), CELULAR VARCHAR(15));
CREATE TABLE CLIENTE (CDCLIENTE INTEGER NOT NULL, IDEMPRESA INTEGER NOT NULL, CLIENTE VARCHAR(100), CGC VARCHAR(15), PRIMARY KEY (CDCLIENTE, IDEMPRESA));
CREATE TABLE MUNICIPIO (CDMUNICIPIO INTEGER NOT NULL PRIMARY KEY, MUNICIPIO VARCHAR(60), UF VARCHAR(2), CDMUNICIPIOIBGE INTEGER);
CREATE TABLE PRODUTO (CDPRODUTO VARCHAR(10) NOT NULL PRIMARY KEY, PRODUTO VARCHAR(150), CDUNIDADE VARCHAR(3), CDUNIDVENDA VARCHAR(3), CDDEPOSITO INTEGER, IDPRECO INTEGER, INATIVO SMALLINT DEFAULT 0);
CREATE TABLE PRODUTOPRECO (CDPRODUTO VARCHAR(10) NOT NULL, IDPRECO INTEGER NOT NULL, CDUNIDADE VARCHAR(3) NOT NULL, PRECO NUMERIC(15,2), VLCUSTO NUMERIC(15,4), PRIMARY KEY (CDPRODUTO, IDPRECO, CDUNIDADE));
CREATE TABLE ORCAMENTO (
  NRORCAMENTO INTEGER NOT NULL,
  IDEMPRESA INTEGER NOT NULL,
  CDCLIENTE INTEGER,
  DTORC DATE,
  HORAORC TIMESTAMP,
  VLTOTAL NUMERIC(15,2),
  CDVENDEDOR INTEGER,
  CDPROPAGANDA INTEGER,
  STATUS INTEGER DEFAULT 0 NOT NULL,
  CLIENTE VARCHAR(100),
  TELEFONE VARCHAR(20),
  CONTATO VARCHAR(70),
  DESCONTO NUMERIC(15,2),
  PERC_DESCONTO NUMERIC(15,4),
  FRETE NUMERIC(15,2),
  INDFINAL SMALLINT,
  PONTUACAO INTEGER,
  SUBTOTAL NUMERIC(15,2),
  LOCALENTR VARCHAR(60),
  BAIRRO VARCHAR(40),
  SUBBAIRRO VARCHAR(40),
  CEP VARCHAR(9),
  UF VARCHAR(2),
  COMPLEMENTO VARCHAR(40),
  REFERENCIA VARCHAR(60),
  TELEFONE_ENTREGA VARCHAR(20),
  CDMUNICIPIO INTEGER,
  IDENDERECO INTEGER,
  CDTPENTREGA VARCHAR(5),
  CDRECEBTO INTEGER,
  CONDPAGTO VARCHAR(30),
  OBSERVACAO VARCHAR(255),
  PRIMARY KEY (NRORCAMENTO, IDEMPRESA)
);
CREATE TABLE ORCPROD (
  POSIC INTEGER NOT NULL,
  NRORCAMENTO INTEGER NOT NULL,
  IDEMPRESA INTEGER NOT NULL,
  CDPRODUTO VARCHAR(10),
  DESCRICAO VARCHAR(150),
  UNID VARCHAR(3),
  QTDPRODUTO NUMERIC(15,3),
  VLUNIT NUMERIC(15,4),
  TOTAL NUMERIC(15,2),
  QTDEPECA NUMERIC(15,3),
  STATUS VARCHAR(2),
  CDDEPOSITO INTEGER,
  DESCONTO NUMERIC(15,2),
  IDPRECO INTEGER,
  ORDEM VARCHAR(1),
  SUBTOTAL NUMERIC(15,2),
  CALC NUMERIC(15,3),
  VLBCICMS NUMERIC(15,2), PERC_ICMS NUMERIC(15,2), VLICMS NUMERIC(15,2), PERC_REDUCAO NUMERIC(15,2),
  VLBCST NUMERIC(15,2), PERC_ST NUMERIC(15,2), VLST NUMERIC(15,2), PERC_REDUCAO_ST NUMERIC(15,2), PERC_COMISS NUMERIC(15,2),
  CDCLIENTE INTEGER,
  HASH VARCHAR(40),
  QTDELIB NUMERIC(15,3),
  VLCUSTO NUMERIC(15,4),
  PRAZOPRODUTO VARCHAR(10),
  RESUMO_OS VARCHAR(100),
  PRIMARY KEY (POSIC, NRORCAMENTO, IDEMPRESA)
);
CREATE GENERATOR GEN_ORCAMENTO;
COMMIT;

